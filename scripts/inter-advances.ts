// Inter's advance widths, from the font files Google Fonts serves, as src/fonts/inter-advances.ts:
//   bun scripts/inter-advances.ts
// Labels are measured with these, so a box fits its text as Inter sets it.
import opentype from 'opentype.js'

const OUT = new URL('../src/fonts/inter-advances.ts', import.meta.url)
const WEIGHTS = [400, 500, 600, 700]
/** What diagram labels mostly hold: Latin, Greek, punctuation, arrows and common symbols. */
const RANGES: [number, number][] = [
  [0x20, 0x7e], [0xa0, 0x17f], [0x370, 0x3ff], [0x2010, 0x2027], [0x2030, 0x203a], [0x2070, 0x209f],
  [0x20ac, 0x20ac], [0x2122, 0x2122], [0x2190, 0x21ff], [0x2212, 0x2212], [0x2260, 0x2265], [0x2713, 0x2717],
]

// An old browser's user agent gets TrueType files, which opentype.js reads.
const css = await (await fetch(`https://fonts.googleapis.com/css2?family=Inter:wght@${WEIGHTS.join(';')}`, { headers: { 'User-Agent': 'Mozilla/4.0' } })).text()
const faces = [...css.matchAll(/font-weight:\s*(\d+);[\s\S]*?src: url\(([^)]+\.ttf)\)/g)].map((m) => ({ weight: Number(m[1]), url: m[2]! }))
const version = css.match(/\/s\/inter\/(v\d+)\//)?.[1]
if (faces.length !== WEIGHTS.length || !version) throw new Error('Google Fonts did not serve Inter at every weight')

const lines: string[] = []
for (const { weight, url } of faces) {
  const font = opentype.parse(await (await fetch(url)).arrayBuffer())
  const widths: string[] = []
  for (const [start, end] of RANGES) {
    for (let code = start; code <= end; code++) {
      const glyph = font.charToGlyph(String.fromCodePoint(code))
      if (glyph && glyph.index !== 0 && glyph.advanceWidth !== undefined) widths.push(`${code}:${Math.round((glyph.advanceWidth / font.unitsPerEm) * 10000) / 10000}`)
    }
  }
  lines.push(`  ${weight}: {${widths.join(',')}},`)
}
await Bun.write(OUT, `// Generated by scripts/inter-advances.ts from Inter ${version} as Google Fonts serves it: each
// character's advance width in em, by weight and code point.

/** Inter's advance widths in em, by weight and code point. */
export const INTER_ADVANCES: Readonly<Record<number, Readonly<Record<number, number>>>> = {
${lines.join('\n')}
}
`)
console.log(`Inter ${version}: ${faces.length} weights written to ${OUT.pathname}`)
